"""
EcoShield AI
Risk Analysis Page

This module renders the deterministic cybersecurity risk results
generated by src/risk_engine.py.

Responsibilities:
- Display the final 0-100 security risk score
- Display the Low / Medium / High risk level
- Display risk-category breakdown
- Explain detected risk factors
- Display uncertainties and sanitization requirements
- Provide navigation to the recommendation page
- Allow the user to return to or restart assessment flow

Risk calculation must NOT be implemented in this module.
This page only presents the RiskAssessment already generated
by src/risk_engine.py.
"""

